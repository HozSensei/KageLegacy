/** @typedef {'stat'|'notable'|'keystone'} NodeType */
/** @typedef {'center'|'taijutsu'|'ninjutsu'|'genjutsu'|'medicine'} Branch */

/**
 * @param {object} n
 * @returns {object}
 */
export function defineNode(n) {
  return {
    id: n.id,
    nameFr: n.nameFr,
    nameEn: n.nameEn,
    descFr: n.descFr || null,
    descEn: n.descEn || null,
    type: n.type,
    x: n.x,
    y: n.y,
    branch: n.branch,
    bonus: n.bonus || null,
    effect: n.effect || null,
    requires: n.requires || [],
    icon: n.icon || (n.type === 'keystone' ? '✦' : n.type === 'notable' ? '◆' : '·'),
    color: n.color || null,
  };
}

const s = partial => defineNode({ type: 'stat', icon: '·', ...partial });
const note = partial => defineNode({ type: 'notable', icon: '◆', ...partial });
const key = partial => defineNode({ type: 'keystone', icon: '✦', ...partial });

