/**
 * Helper nœud.
 * @param {object} n
 */
function node(n) {
  return {
    node_id: n.id,
    name_fr: n.nameFr,
    name_en: n.nameEn,
    description_fr: n.descFr || null,
    description_en: n.descEn || null,
    type: n.type,
    position_x: n.x,
    position_y: n.y,
    branch: n.branch,
    stat_bonus_json: n.bonus ? JSON.stringify(n.bonus) : null,
    effect_code: n.effect || null,
    requires_nodes_json: JSON.stringify(n.requires || []),
    icon: n.icon || null,
    color: n.color || null,
  };
}

