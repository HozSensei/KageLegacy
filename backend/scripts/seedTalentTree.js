async function upsertNode(n) {
  await query(
    `INSERT INTO talent_tree_nodes
      (node_id, name_fr, name_en, description_fr, description_en, type,
       position_x, position_y, branch, stat_bonus_json, effect_code,
       requires_nodes_json, icon, color)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
     ON DUPLICATE KEY UPDATE
       name_fr = VALUES(name_fr),
       name_en = VALUES(name_en),
       description_fr = VALUES(description_fr),
       description_en = VALUES(description_en),
       type = VALUES(type),
       position_x = VALUES(position_x),
       position_y = VALUES(position_y),
       branch = VALUES(branch),
       stat_bonus_json = VALUES(stat_bonus_json),
       effect_code = VALUES(effect_code),
       requires_nodes_json = VALUES(requires_nodes_json),
       icon = VALUES(icon),
       color = VALUES(color)`,
    [
      n.node_id,
      n.name_fr,
      n.name_en,
      n.description_fr,
      n.description_en,
      n.type,
      n.position_x,
      n.position_y,
      n.branch,
      n.stat_bonus_json,
      n.effect_code,
      n.requires_nodes_json,
      n.icon,
      n.color,
    ],
  );
}

async function main() {
  console.log(`Seeding talent tree (${NODES.length} nodes)…`);

  const byType = { stat: 0, notable: 0, keystone: 0 };
  const byBranch = {};

  for (const n of NODES) {
    // Constraint: notables/keystones need effect_code; stats need bonus.
    if (n.type === 'stat' && !n.stat_bonus_json) {
      throw new Error(`Stat node ${n.node_id} missing bonus`);
    }
    if ((n.type === 'notable' || n.type === 'keystone') && !n.effect_code) {
      throw new Error(`${n.type} node ${n.node_id} missing effect_code`);
    }
    await upsertNode(n);
    byType[n.type] += 1;
    byBranch[n.branch] = (byBranch[n.branch] || 0) + 1;
  }

  console.log('Done.');
  console.log('By type:', byType);
  console.log('By branch:', byBranch);
  process.exit(0);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
